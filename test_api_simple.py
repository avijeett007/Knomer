def test_credits_endpoint(api_key):
    """Test credits endpoint with authentication"""
    print("\n🧪 Testing credits endpoint...")
    
    try:
        headers = {"Authorization": f"Bearer {api_key}"}
        response = requests.get(f"{API_BASE_URL}/credits", headers=headers)
        
        if response.status_code == 401:
            print("⚠️  Authentication failed - API key might be invalid")
            return False
        
        assert response.status_code == 200, f"Expected 200, got {response.status_code}"
        
        data = response.json()
        assert "total_credits" in data, "Response missing 'total_credits' field"
        assert "remaining_credits" in data, "Response missing 'remaining_credits' field"
        
        print(f"✅ Credits check passed: {data['remaining_credits']} credits available")
        return True
        
    except Exception as e:
        print(f"❌ Credits endpoint failed: {e}")
        return False

def test_credit_estimation(api_key):
    """Test credit estimation endpoint"""
    print("\n🧪 Testing credit estimation...")
    
    try:
        headers = {"Authorization": f"Bearer {api_key}"}
        
        estimation_data = {
            "job_type": "simple_merge",
            "videos": [
                {"url": "https://example.com/video1.mp4", "duration": 30.0, "order_index": 0},
                {"url": "https://example.com/video2.mp4", "duration": 45.0, "order_index": 1}
            ],
            "processing_options": {
                "platform": "youtube",
                "quality_preset": "balanced"
            }
        }
        
        response = requests.post(
            f"{API_BASE_URL}/credits/estimate",
            json=estimation_data,
            headers=headers
        )
        
        assert response.status_code == 200, f"Expected 200, got {response.status_code}"
        
        data = response.json()
        assert "estimated_credits" in data, "Response missing 'estimated_credits' field"
        assert "breakdown" in data, "Response missing 'breakdown' field"
        
        print(f"✅ Credit estimation passed: {data['estimated_credits']} credits estimated")
        print(f"   Breakdown: {data['breakdown']}")
        return True
        
    except Exception as e:
        print(f"❌ Credit estimation failed: {e}")
        return False

def test_job_creation(api_key):
    """Test job creation endpoint"""
    print("\n🧪 Testing job creation...")
    
    try:
        headers = {"Authorization": f"Bearer {api_key}"}
        
        job_data = {
            "job_type": "simple_merge",
            "videos": [
                {"url": "https://example.com/video1.mp4", "order_index": 0},
                {"url": "https://example.com/video2.mp4", "order_index": 1}
            ],
            "processing_options": {
                "platform": "youtube",
                "quality_preset": "fast"
            }
        }
        
        response = requests.post(
            f"{API_BASE_URL}/jobs",
            json=job_data,
            headers=headers
        )
        
        if response.status_code == 402:
            print("⚠️  Insufficient credits for job creation")
            return False
        
        assert response.status_code == 200, f"Expected 200, got {response.status_code}"
        
        data = response.json()
        assert "id" in data, "Response missing 'id' field"
        assert "status" in data, "Response missing 'status' field"
        
        job_id = data["id"]
        print(f"✅ Job creation passed: {job_id}")
        print(f"   Status: {data['status']}")
        print(f"   Estimated credits: {data.get('estimated_credits', 0)}")
        
        # Test job status endpoint
        status_response = requests.get(f"{API_BASE_URL}/jobs/{job_id}", headers=headers)
        assert status_response.status_code == 200, "Job status check failed"
        
        status_data = status_response.json()
        print(f"✅ Job status check passed: {status_data['job']['status']}")
        
        return True
        
    except Exception as e:
        print(f"❌ Job creation failed: {e}")
        return False

