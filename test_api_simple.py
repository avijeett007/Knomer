def main():
    """Main test function"""
    print("🎯 Video Processing API - Simple Test Suite")
    print("=" * 50)
    
    # Wait for API to be ready
    if not wait_for_api():
        sys.exit(1)
    
    # Get test API key
    api_key = get_test_api_key()
    if not api_key:
        print("❌ No test API key available")
        sys.exit(1)
    
    print(f"🔑 Using API key: {api_key[:20]}...")
    
    # Run tests
    tests = [
        ("Health Endpoint", test_health_endpoint, []),
        ("Root Endpoint", test_root_endpoint, []),
        ("Credits Endpoint", test_credits_endpoint, [api_key]),
        ("Credit Estimation", test_credit_estimation, [api_key]),
        ("Job Creation", test_job_creation, [api_key]),
        ("Jobs Listing", test_jobs_list, [api_key])
    ]
    
    results = {}
    
    for test_name, test_func, args in tests:
        try:
            results[test_name] = test_func(*args)
        except Exception as e:
            print(f"❌ {test_name} crashed: {e}")
            results[test_name] = False
    
    # Summary
    print("\n" + "=" * 50)
    print("📊 Test Summary")
    print("=" * 50)
    
    passed = 0
    total = len(results)
    
    for test_name, result in results.items():
        status = "✅ PASSED" if result else "❌ FAILED"
        print(f"{test_name}: {status}")
        if result:
            passed += 1
    
    print(f"\nResults: {passed}/{total} tests passed")
    
    if passed == total:
        print("🎉 All tests passed!")
        sys.exit(0)
    else:
        print("💥 Some tests failed!")
        sys.exit(1)

if __name__ == "__main__":
    main()
