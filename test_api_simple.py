#!/usr/bin/env python3
"""
Simple API test script for Docker environment
"""
import requests
import json
import time
import sys
import os

API_BASE_URL = "http://localhost:8001"

def wait_for_api(max_retries=30):
    """Wait for API to be ready"""
    print("🔍 Waiting for API to be ready...")
    
    for i in range(max_retries):
        try:
            response = requests.get(f"{API_BASE_URL}/health", timeout=5)
            if response.status_code == 200:
                print("✅ API is ready!")
                return True
        except requests.exceptions.RequestException:
            pass
        
        print(f"⏳ Waiting... ({i+1}/{max_retries})")
        time.sleep(2)
    
    print("❌ API failed to start")
    return False

def get_test_api_key():
    """Get test API key from database setup"""
    try:
        # Read test data if available
        test_data_file = "/app/test_data.json"
        if os.path.exists(test_data_file):
            with open(test_data_file, 'r') as f:
                test_data = json.load(f)
                return test_data.get('api_key')
    except Exception as e:
        print(f"⚠️  Could not read test data: {e}")
    
    # Default test API key (from sqlite_setup.py)
    return "vp_test_key_12345"  # This will be generated by setup

def test_health_endpoint():
    """Test health endpoint"""
    print("\n🧪 Testing health endpoint...")
    
    try:
        response = requests.get(f"{API_BASE_URL}/health")
        assert response.status_code == 200, f"Expected 200, got {response.status_code}"
        
        data = response.json()
        assert "status" in data, "Response missing 'status' field"
        assert "services" in data, "Response missing 'services' field"
        
        print(f"✅ Health check passed: {data['status']}")
        return True
        
    except Exception as e:
        print(f"❌ Health check failed: {e}")
        return False

def test_root_endpoint():
    """Test root endpoint"""
